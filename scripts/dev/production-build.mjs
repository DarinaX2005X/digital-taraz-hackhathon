import { createHash } from "node:crypto";
import { lstat, readFile, readdir, realpath, rm, stat, unlink } from "node:fs/promises";
import path from "node:path";
import { CliError } from "./errors.mjs";
import { dependencyHash } from "./dependencies.mjs";
import { writeJsonAtomic } from "./runtime.mjs";

export const productionDistDir = ".local-data/build";
const manifestName = "tirlik-build.json";
const inputDirectories = ["src", "public", "migrations", "fixtures"];
const inputFiles = ["next.config.ts", "package.json", "package-lock.json", "tsconfig.json"];
const generatedDirectories = new Set(["src/app/.well-known/workflow/v1"]);

const normalized = (value) => process.platform === "win32" ? value.toLowerCase() : value;

async function filesUnder(root, relativeDirectory) {
  const relativeDirectoryPosix = relativeDirectory.replaceAll("\\", "/");
  if (generatedDirectories.has(relativeDirectoryPosix)) return [];
  const directory = path.join(root, relativeDirectory);
  let entries;
  try {
    const info = await lstat(directory);
    if (!info.isDirectory() || info.isSymbolicLink()) throw new CliError("BUILD_INPUT_UNSAFE", `Cannot fingerprint ${relativeDirectory}.`, "Replace linked or special build inputs with ordinary project files.");
    entries = await readdir(directory, { withFileTypes: true });
  } catch (error) {
    if (error.code === "ENOENT") return [];
    throw error;
  }
  const found = [];
  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    const relative = path.posix.join(relativeDirectoryPosix, entry.name);
    if (entry.isSymbolicLink()) throw new CliError("BUILD_INPUT_UNSAFE", `Cannot fingerprint linked input ${relative}.`, "Replace linked build inputs with ordinary project files.");
    if (entry.isDirectory()) found.push(...await filesUnder(root, relative));
    else if (entry.isFile()) found.push(relative);
    else throw new CliError("BUILD_INPUT_UNSAFE", `Cannot fingerprint special input ${relative}.`, "Replace special build inputs with ordinary project files.");
  }
  return found;
}

export async function productionInputHash(root, env = process.env) {
  const canonicalRoot = await realpath(root);
  const files = [...inputFiles];
  for (const directory of inputDirectories) files.push(...await filesUnder(canonicalRoot, directory));
  files.sort();
  // next-env.d.ts and the Workflow well-known tree are regenerated by next build.
  const hash = createHash("sha256").update("tirlik-production-input-v2\0");
  for (const relative of files) {
    const absolute = path.join(canonicalRoot, relative);
    let content;
    try { content = await readFile(absolute); } catch (error) { if (error.code === "ENOENT") continue; throw error; }
    hash.update(`${relative.length}:${relative}:${content.length}:`).update(content).update("\0");
  }
  const publicEnvironment = Object.entries(env)
    .filter(([name, value]) => (name.startsWith("NEXT_PUBLIC_") || name === "WORKFLOW_TARGET_WORLD") && typeof value === "string")
    .sort(([left], [right]) => left.localeCompare(right));
  for (const [name, value] of publicEnvironment) hash.update(`env:${name.length}:${name}:${value.length}:`).update(value).update("\0");
  return hash.digest("hex");
}

async function buildDirectory(root) {
  const canonicalRoot = await realpath(root);
  const expected = path.join(canonicalRoot, ...productionDistDir.split("/"));
  let info;
  try { info = await lstat(expected); } catch (error) {
    if (error.code === "ENOENT") throw new CliError("PRODUCTION_BUILD_MISSING", "The local production build is missing.", "Run node scripts/check-build.mjs after the current source is stable.");
    throw error;
  }
  if (!info.isDirectory() || info.isSymbolicLink() || normalized(await realpath(expected)) !== normalized(expected)) {
    throw new CliError("PRODUCTION_BUILD_UNSAFE", "The local production build directory is not an ordinary owned directory.", "Preserve it for inspection and rebuild with node scripts/check-build.mjs.");
  }
  return { root: canonicalRoot, directory: expected };
}

async function readBuildOutput(root) {
  const build = await buildDirectory(root);
  const requiredFiles = ["BUILD_ID", "required-server-files.json", "routes-manifest.json", "prerender-manifest.json"];
  const requiredDirectories = ["server", "static"];
  for (const relative of requiredFiles) {
    const info = await lstat(path.join(build.directory, relative)).catch(() => null);
    if (!info?.isFile() || info.isSymbolicLink()) throw new CliError("PRODUCTION_BUILD_INCOMPLETE", `The production build is missing ${relative}.`, "Run node scripts/check-build.mjs after the current source is stable.");
  }
  for (const relative of requiredDirectories) {
    const info = await lstat(path.join(build.directory, relative)).catch(() => null);
    if (!info?.isDirectory() || info.isSymbolicLink()) throw new CliError("PRODUCTION_BUILD_INCOMPLETE", `The production build is missing ${relative}/.`, "Run node scripts/check-build.mjs after the current source is stable.");
  }
  const buildId = (await readFile(path.join(build.directory, "BUILD_ID"), "utf8")).trim();
  if (!/^[A-Za-z0-9_-]{1,128}$/.test(buildId)) throw new CliError("PRODUCTION_BUILD_INCOMPLETE", "The production BUILD_ID is invalid.", "Run node scripts/check-build.mjs after the current source is stable.");
  let required;
  try { required = JSON.parse(await readFile(path.join(build.directory, "required-server-files.json"), "utf8")); } catch {
    throw new CliError("PRODUCTION_BUILD_INCOMPLETE", "The production server manifest is invalid.", "Run node scripts/check-build.mjs after the current source is stable.");
  }
  if (required?.config?.distDir !== productionDistDir || normalized(required?.appDir ?? "") !== normalized(build.root) || !Array.isArray(required.files)) {
    throw new CliError("PRODUCTION_BUILD_FOREIGN", "The production build does not belong to this checkout and dist directory.", "Preserve it for inspection and rebuild with node scripts/check-build.mjs.");
  }
  return { ...build, buildId };
}

export async function invalidateProductionBuild(root) {
  const manifest = path.join(root, ...productionDistDir.split("/"), manifestName);
  await unlink(manifest).catch((error) => { if (error.code !== "ENOENT") throw error; });
}

export async function recordProductionBuild(root, { inputHash, env = process.env, lockHash } = {}) {
  const output = await readBuildOutput(root);
  const currentInputHash = await productionInputHash(output.root, env);
  if (!inputHash || currentInputHash !== inputHash) {
    await invalidateProductionBuild(output.root);
    throw new CliError("BUILD_INPUT_CHANGED", "Project inputs changed while the production build was running.", "Wait for writers to stop, then rerun node scripts/check-build.mjs.");
  }
  const actualLockHash = lockHash ?? await dependencyHash(output.root);
  const packageJson = JSON.parse(await readFile(path.join(output.root, "package.json"), "utf8"));
  const manifest = {
    version: 1,
    distDir: productionDistDir,
    buildId: output.buildId,
    inputHash: currentInputHash,
    lockHash: actualLockHash,
    nextVersion: packageJson.dependencies?.next,
    createdAt: new Date().toISOString(),
  };
  if (typeof manifest.nextVersion !== "string") throw new CliError("PRODUCTION_BUILD_INCOMPLETE", "The Next.js version is not pinned in package.json.", "Restore package.json and rebuild.");
  await writeJsonAtomic(path.join(output.directory, manifestName), manifest);
  return manifest;
}

export async function verifyProductionBuild(root, { env = process.env, lockHash } = {}) {
  const output = await readBuildOutput(root);
  let manifest;
  try { manifest = JSON.parse(await readFile(path.join(output.directory, manifestName), "utf8")); } catch {
    throw new CliError("PRODUCTION_BUILD_UNVERIFIED", "The production build has no completed Tirlik manifest.", "Run node scripts/check-build.mjs after the current source is stable.");
  }
  const packageJson = JSON.parse(await readFile(path.join(output.root, "package.json"), "utf8"));
  const actualInputHash = await productionInputHash(output.root, env);
  const actualLockHash = lockHash ?? await dependencyHash(output.root);
  if (manifest?.version !== 1 || manifest.distDir !== productionDistDir || manifest.buildId !== output.buildId
    || manifest.inputHash !== actualInputHash || manifest.lockHash !== actualLockHash
    || manifest.nextVersion !== packageJson.dependencies?.next || !Number.isFinite(Date.parse(manifest.createdAt ?? ""))) {
    throw new CliError("PRODUCTION_BUILD_STALE", "The production build does not match the current project inputs.", "Run node scripts/check-build.mjs after the current source is stable.");
  }
  return manifest;
}

async function directoryBytes(directory) {
  let bytes = 0;
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const child = path.join(directory, entry.name);
    if (entry.isSymbolicLink()) throw new CliError("PRODUCTION_CACHE_UNSAFE", "The compiler cache contains a link.", "Preserve the cache for inspection and remove it manually after verifying ownership.");
    if (entry.isDirectory()) bytes += await directoryBytes(child);
    else if (entry.isFile()) bytes += (await stat(child)).size;
    else throw new CliError("PRODUCTION_CACHE_UNSAFE", "The compiler cache contains a special file.", "Preserve the cache for inspection and remove it manually after verifying ownership.");
  }
  return bytes;
}

export async function pruneProductionCompilerCache(root) {
  const output = await readBuildOutput(root);
  const cache = path.join(output.directory, "cache");
  let cacheInfo;
  try { cacheInfo = await lstat(cache); } catch (error) { if (error.code === "ENOENT") return { removed: 0, bytes: 0 }; throw error; }
  if (!cacheInfo.isDirectory() || cacheInfo.isSymbolicLink() || normalized(await realpath(cache)) !== normalized(cache)) {
    throw new CliError("PRODUCTION_CACHE_UNSAFE", "The production cache is not an ordinary owned directory.", "Preserve it for inspection and remove it manually after verifying ownership.");
  }
  let removed = 0;
  let bytes = 0;
  for (const name of ["webpack", "swc"]) {
    const target = path.join(cache, name);
    let info;
    try { info = await lstat(target); } catch (error) { if (error.code === "ENOENT") continue; throw error; }
    if (!info.isDirectory() || info.isSymbolicLink() || path.dirname(target) !== cache || normalized(await realpath(target)) !== normalized(target)) {
      throw new CliError("PRODUCTION_CACHE_UNSAFE", `The production ${name} cache is not an ordinary owned directory.`, "Preserve it for inspection and remove it manually after verifying ownership.");
    }
    bytes += await directoryBytes(target);
    await rm(target, { recursive: true, force: false, maxRetries: 3, retryDelay: 100 });
    removed += 1;
  }
  return { removed, bytes };
}
